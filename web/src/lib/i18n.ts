const dictionaries: Record<Locale, Dict> = {
  "zh-TW": zhTW,
  "zh-CN": zhCN,
  "en": en,
  "ja": ja,
  "ko": ko,
};

/**
 * Hook returning a translation function bound to the current locale.
 * Falls back to zh-TW (the project default) and finally to the key itself.
 */
export function useT() {
  const locale = useLocaleStore((s) => s.locale);
  const dict = dictionaries[locale] ?? zhTW;
  return (key: string, fallback?: string): string => {
    return dict[key] ?? zhTW[key] ?? fallback ?? key;
  };
}

/** Non-hook variant for use outside React components. */
export function translate(locale: Locale, key: string): string {
  const dict = dictionaries[locale] ?? zhTW;
  return dict[key] ?? zhTW[key] ?? key;
}
